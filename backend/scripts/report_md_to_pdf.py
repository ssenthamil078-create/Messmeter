#!/usr/bin/env python3
"""Convert the daily markdown report artifact to a PDF using ReportLab.
The script reads the markdown file generated by the agent and writes a PDF
named `daily_report_YYYY-MM-DD.pdf` in the same directory.
"""
import os
from pathlib import Path

from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Preformatted

# Path to the markdown artifact (relative to this script)
ARTIFACT_DIR = Path(__file__).resolve().parents[2] / "brain" / "920a4ccb-bfad-45fc-bc26-0261cf5c21d9"
MARKDOWN_FILE = ARTIFACT_DIR / "daily_report_2026-11-27.md"
PDF_FILE = ARTIFACT_DIR / "daily_report_2026-11-27.pdf"

if not MARKDOWN_FILE.is_file():
    raise FileNotFoundError(f"Markdown report not found: {MARKDOWN_FILE}")

# Read markdown content
with open(MARKDOWN_FILE, "r", encoding="utf-8") as f:
    markdown_text = f.read()

# Simple conversion: keep headings and tables as preformatted text.
# For a quick visual we will treat the whole content as a Preformatted block.
styles = getSampleStyleSheet()
story = []
story.append(Paragraph("Daily Report PDF", styles["Title"]))
story.append(Spacer(1, 12))
story.append(Preformatted(markdown_text, style=styles["Code"]))

# Build PDF
doc = SimpleDocTemplate(str(PDF_FILE), pagesize=LETTER)
doc.build(story)

print(f"PDF generated at {PDF_FILE}")
